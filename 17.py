num1 = int(input("Enter a no. here: "))

sign = input("Enter operation here: ")

num2 = int(input("Enter a no. here: "))

if sign == "+" :
    print(num1 + num2)

elif sign == "-" :
    print(num1 - num2)

elif sign == "*" :
    print(num1 * num2)

elif sign == "/" :
    print(num1 / num2)                

